#!/usr/bin/env python3
# Builds the shell's translations from en.py: en.json (read at run time by the C++ programs via
# tr.h) and a Tr.js copy in every QML tree (import "Tr.js" as Tr; Tr.t("Русский текст")).
# Usage: build.py OUT/en.json QML_DIR...   (build.sh passes the repository's QML trees)
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from en import EN  # noqa: E402

out_json, qml_dirs = sys.argv[1], sys.argv[2:]
os.makedirs(os.path.dirname(os.path.abspath(out_json)), exist_ok=True)
with open(out_json, "w") as f:
    json.dump(EN, f, ensure_ascii=False, indent=0, sort_keys=True)

js = """// Generated by i18n/build.py from i18n/en.py: edit there, not here.
// UI text is written in Russian; any other UI language gets English.
.pragma library

var en = %s;

var ru = String(Qt.uiLanguage || Qt.locale().uiLanguages[0] || Qt.locale().name).toLowerCase().indexOf("ru") === 0;

function t(s) {
    if (ru) return s;
    var e = en[s];
    return e === undefined ? s : e;
}

// dates and numbers in the UI language
function locale() {
    return Qt.locale(ru ? "ru_RU" : "en_US");
}
""" % json.dumps(EN, ensure_ascii=False, indent=0, sort_keys=True)

for d in qml_dirs:
    with open(os.path.join(d, "Tr.js"), "w") as f:
        f.write(js)
print(len(EN), "strings")
